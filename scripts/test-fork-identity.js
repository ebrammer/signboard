const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const { APP_NAME, APP_ID, UPDATES_ENABLED } = require('../lib/forkIdentity');
const { getDefaultDesktopUserDataDir } = require('../lib/boardDiscovery');
const config = require('../electron-builder.json');
assert.equal(APP_ID, 'com.syllabi.signboard');
assert.equal(config.appId, APP_ID);
assert.equal(config.productName, APP_NAME);
assert.equal(require('../package.json').productName, APP_NAME);
assert.equal(config.publish, null);
assert.equal(UPDATES_ENABLED, false);
assert.equal(getDefaultDesktopUserDataDir({ platform: 'darwin', homeDir: '/Users/test', env: {} }), '/Users/test/Library/Application Support/Syllabi Signboard');
assert.equal(getDefaultDesktopUserDataDir({ platform: 'darwin', homeDir: '/Users/test', env: { SIGNBOARD_DESKTOP_USER_DATA_DIR: '/tmp/isolated' } }), '/tmp/isolated');
assert.equal(getDefaultDesktopUserDataDir({ platform: 'win32', homeDir: '/home/test', env: { APPDATA: '/profiles/test' } }), path.resolve('/profiles/test/Syllabi Signboard'));
assert.equal(getDefaultDesktopUserDataDir({ platform: 'linux', homeDir: '/home/test', env: {} }), '/home/test/.config/Syllabi Signboard');
const main = fs.readFileSync(path.join(__dirname, '../main.js'), 'utf8');
assert.match(main, /async function checkForUpdates\([^]*?if \(!UPDATES_ENABLED\)/);
assert.match(main, /function setupAutoUpdater\(\) \{\s*if \(!UPDATES_ENABLED/);
console.log('Fork identity, isolated profile defaults/override, and upstream update gates passed.');
